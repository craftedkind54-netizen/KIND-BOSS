function categoriesFor(targetRank) {
  if (!Object.hasOwn(RANK_CATEGORIES, targetRank)) throw new RangeError('Unknown interview rank or category');
  return RANK_CATEGORIES[targetRank].map(({qs, evaluation, ...meta}) => meta);
}

function categoryFor(targetRank, index) {
  const category = RANK_CATEGORIES[targetRank]?.[index];
  if (!category) throw new RangeError('Unknown interview rank or category');
  return {...category, qs: [...category.qs], focus: FOCUS[targetRank]};
}

function snapshot(targetRank) {
  return RANK_CATEGORIES[targetRank].map((_, index) => categoryFor(targetRank, index));
}

